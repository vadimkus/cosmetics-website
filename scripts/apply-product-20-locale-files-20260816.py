def js(obj):
    """Single-quoted JS string literal holding compact JSON."""
    return "'" + json.dumps(obj, ensure_ascii=False, separators=(',', ':')).replace("'", "\\'") + "'"


def dq(s):
    return '"' + s.replace('"', '\\"') + '"'


