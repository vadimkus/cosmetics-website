/**
 * Service Worker Version Generator
 * 
 * This script updates the service worker cache names with the current
 * package.json version to ensure cache invalidation on version updates.
 * 
 * Run as part of the build process.
 */

const fs = require('fs')
const path = require('path')
const crypto = require('crypto')

// Read package.json version
const packageJsonPath = path.join(__dirname, '..', 'package.json')
const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'))
const version = packageJson.version

// Generate a short hash from build time + version for uniqueness
const buildHash = crypto
  .createHash('md5')
  .update(`${version}-${new Date().toISOString().slice(0, 10)}`)
  .digest('hex')
  .slice(0, 8)

// Create version string
const versionString = `v${version}-${buildHash}`

console.log(`📦 Generating service worker version: ${versionString}`)

// Read the service worker template
const swPath = path.join(__dirname, '..', 'public', 'sw.js')
let swContent = fs.readFileSync(swPath, 'utf8')

// Replace version patterns
// Match patterns like: 'genosys-cache-v58' or 'genosys-static-v0.1.0-abc123'
// This regex handles both old numeric versions and new semver+hash versions
const cacheVersionRegex = /(genosys-(?:cache|static|dynamic|images|products|api|pages))-v[\d.]+(?:-[a-f0-9]+)?(?:\.[\d.]+-[a-f0-9]+)?/g

// Count replacements for logging
let replacementCount = 0

swContent = swContent.replace(cacheVersionRegex, (match, prefix) => {
  replacementCount++
  return `${prefix}-${versionString}`
})

// Write back the updated service worker
fs.writeFileSync(swPath, swContent, 'utf8')

console.log(`✅ Updated ${replacementCount} cache version references`)
console.log(`   Cache names now use: ${versionString}`)

// Also create a version file that can be imported
const versionFilePath = path.join(__dirname, '..', 'lib', 'swVersion.ts')
const versionFileContent = `// Auto-generated by scripts/generate-sw-version.js
// Do not edit manually - this file is regenerated on each build

export const SW_VERSION = '${versionString}'
export const APP_VERSION = '${version}'
export const BUILD_HASH = '${buildHash}'
export const BUILD_DATE = '${new Date().toISOString()}'
`

fs.writeFileSync(versionFilePath, versionFileContent, 'utf8')
console.log(`✅ Generated lib/swVersion.ts`)
